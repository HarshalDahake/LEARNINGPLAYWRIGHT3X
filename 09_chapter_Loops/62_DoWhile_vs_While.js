
let a = 10;
while (a < 10) 
{
    console.log(a);
    a++;
}
console.log("----------------------");

// while loop will not execute the code block if the condition is false.

let b = 10;
do 
{
    console.log(b);
    b++;
} 
while (b < 10);

/* do while loop will execute the code block at least once, 
   even if the condition is false. */
